#!/usr/bin/env node
/**
 * Sync contract ABIs and deployment addresses from the Foundry workspace into the web app.
 *
 *   node scripts/sync-contracts.mjs
 *
 * Reads  contracts/out/<Name>.sol/<Name>.json   (requires `forge build`)
 *        contracts/deployments/<chainId>.json    (written by script/Deploy.s.sol)
 * Writes src/lib/generated/abis.ts and src/lib/generated/deployments.ts (both committed so
 * Vercel builds do not need Foundry).
 */
import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const deploymentsDir = join(root, "contracts", "deployments");
const target = join(root, "src", "lib", "generated");

const CONTRACTS = {
  token: "PWSIToken",
  faucet: "PWSIFaucet",
  treasury: "BuybackBurnTreasury",
  territory: "PlanetTerritory",
  marketplace: "TerritoryMarketplace",
  ops: "PlanetOps",
};

const header = "// AUTO-GENERATED by scripts/sync-contracts.mjs — do not edit by hand.\n\n";

let abis = header;
for (const [key, name] of Object.entries(CONTRACTS)) {
  const file = join(out, `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) throw new Error(`Missing ${file}. Run \`forge build\` in contracts/ first.`);
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  abis += `export const ${key}Abi = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(target, "abis.ts"), abis);

const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    // On Arbitrum-based chains (Robinhood Chain) Solidity's block.number is the *L1* block, so the
    // value recorded by Deploy.s.sol is not a valid L2 log-scan start. Prefer the earliest L2
    // receipt from the forge broadcast when it exists.
    let deployBlock = d.deployBlock;
    const run = join(root, "contracts", "broadcast", "Deploy.s.sol", String(d.chainId), "run-latest.json");
    if (existsSync(run)) {
      const receipts = JSON.parse(readFileSync(run, "utf8")).receipts ?? [];
      const blocks = receipts.map((r) => parseInt(r.blockNumber, 16)).filter(Number.isFinite);
      if (blocks.length) deployBlock = Math.min(...blocks);
    }
    deployments[d.chainId] = {
      chainId: d.chainId,
      deployBlock,
      token: d.token,
      faucet: d.faucet,
      treasury: d.treasury,
      territory: d.territory,
      marketplace: d.marketplace,
      ops: d.ops,
    };
  }
}
const dep =
  header +
  `import type { Address } from "viem";\n\n` +
  `export type Deployment = {\n  chainId: number;\n  deployBlock: number;\n  token: Address;\n  faucet: Address;\n  treasury: Address;\n  territory: Address;\n  marketplace: Address;\n  ops: Address;\n};\n\n` +
  `export const deployments: Record<number, Deployment> = ${JSON.stringify(deployments, null, 2)};\n`;
writeFileSync(join(target, "deployments.ts"), dep);
console.log(`Synced ${Object.keys(CONTRACTS).length} ABIs, deployments for chains: ${Object.keys(deployments).join(", ") || "none"}`);
